import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import YAML from 'yaml';

const contractPath = resolve('contracts/openapi.yaml');
const assetPath = resolve('apps/web/src/assets/openapi.yaml');
const generatedPath = resolve('apps/web/src/app/openapi.generated.ts');

const yamlSource = await readFile(contractPath, 'utf8');
const document = YAML.parse(yamlSource);

await mkdir(dirname(assetPath), { recursive: true });
await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(assetPath, yamlSource);
await writeFile(
  generatedPath,
  `/* This file is generated by scripts/sync-openapi-web.mjs from contracts/openapi.yaml. */\n` +
    `/* eslint-disable */\n` +
    `export const OPENAPI_DOCUMENT = ${JSON.stringify(document, null, 2)} as const;\n`,
);
